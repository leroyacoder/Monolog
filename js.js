        if (srok >= srokObnovleniya) return;
        srokObnovleniya = srok;
        window.clearTimeout(tayminObnovleniya);
        tayminObnovleniya = window.setTimeout(obnovitSistemu, cherez);
        window.clearTimeout(tayminUvedomleniya);
